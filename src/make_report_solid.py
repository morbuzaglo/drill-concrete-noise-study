def fl(x): return float(str(x).replace('−', '-'))


def f1(x, n=1, sign=False):
    x = 0.0 if abs(x) < 0.5 * 10 ** -n else x
    return (f'{x:+.{n}f}' if sign else f'{x:.{n}f}').replace('-', '−')


def rcsv(name):
    p = RES / name
    if not p.exists(): return None
    with open(p, encoding='utf-8') as fh: return list(csv.reader(fh))


SENS_CSV = RES / 'tables' / 'solid_sensitivity_bands.csv'


def sens_levels(cid, tag):
    """band levels (mic F) of a sensitivity run. Computed from the (untracked, large) npz when present and cached in a CSV; otherwise read from the CSV."""
    key = f'{cid}{tag}'; rows = {}
    if SENS_CSV.exists():
        with open(SENS_CSV, encoding='utf-8') as fh: rows = {r[0]: [float(x) for x in r[1:]] for r in list(csv.reader(fh))[1:]}
    if (RES / f'ccx_{cid}{tag}.npz').exists():
        f, pr, _ = pressure(cid, tag); rows[key] = list(tf_band_level(f, pr[:, :1], AS.B)[:, 0])
        with open(SENS_CSV, 'w', newline='', encoding='utf-8') as fh:
            w = csv.writer(fh); w.writerow(['run'] + [f'{b}Hz' for b in BL])
            for k, v in sorted(rows.items()): w.writerow([k] + [f'{x:.3f}' for x in v])
    return np.array(rows[key]) if key in rows else None


