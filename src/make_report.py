def f1(x, n=1, sign=False):
    return (f'{x:+.{n}f}' if sign else f'{x:.{n}f}').replace('-', '−')


def rng_txt(a, n=1):
    return f'{f1(np.min(a), n)} עד {f1(np.max(a), n)}'


def png(sub, name): return FIG / sub / f'{name}.fallback.png'


