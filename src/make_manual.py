def build_toc(d, anchor):
    """Static table of contents (RTL table, text on the right, page number on the left) inserted before the anchor paragraph.
    Page numbers come from toc_pages.json (written by manual_pages.py after a first build)."""
    pf = ROOT / 'report' / 'toc_pages.json'
    pages = json.loads(pf.read_text()) if pf.exists() else []
    if len(pages) != len(HEADS): pages = ['' for _ in HEADS]
    for (lvl, text), pg in zip(HEADS, pages):
        t = d.add_table(rows=1, cols=2); t._tbl.tblPr.append(OxmlElement('w:bidiVisual'))
        c0, c1 = t.rows[0].cells; c0.width = Cm(15.0); c1.width = Cm(1.4)
        p0 = c0.paragraphs[0]; _bidi(p0); p0.paragraph_format.space_after = Pt(0); p0.paragraph_format.space_before = Pt(3 if lvl == 1 else 0)
        if lvl == 2:
            ppr = p0._p.get_or_add_pPr(); ind = OxmlElement('w:ind'); ind.set(qn('w:right'), '500'); ppr.append(ind)
        txt = re.sub(r'^(\d+)\.\s', lambda m: m.group(1) + '  ', text)
        add_text(p0, txt, bold=(lvl == 1), size=10.5 if lvl == 1 else 10)
        p1 = c1.paragraphs[0]; p1.paragraph_format.space_after = Pt(0); p1.paragraph_format.space_before = Pt(3 if lvl == 1 else 0)
        r = p1.add_run(str(pg)); r.font.size = Pt(10)
        anchor._p.addprevious(t._tbl)


