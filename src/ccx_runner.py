"""CalculiX 2.22 driver: writes the .inp (C3D8I solid, SPRINGA/DASHPOTA soil impedance), runs modal + steady-state dynamics,
parses nodal complex displacement on the exposed surface. Units SI. CalculiX phasor convention is verified by cross-check."""
import os, re, subprocess, time, pathlib
import numpy as np
import scipy.sparse as sp

CCX = os.path.join(os.environ['LOCALAPPDATA'], 'CalculiX', 'ccx_static.exe')

# frequency bands (uniform spacing inside each band, bias=1): (f1, f2, n)
def default_bands(fmin=44.19, fmax=1414.3, n_per_interval=12):
    """One SSD step. CalculiX places n points in EACH interval between consecutive eigenfrequencies (bias 3 clusters them
    at the resonances), so the total number of frequencies is about n x (number of modes in the range)."""
    return [(fmin, fmax, n_per_interval)]


def band_freqs(bands):
    fr = [np.linspace(a, b, n) for a, b, n in bands]
    return fr


def _fmt(v):
    return ('%.9e' % v)


def surface_nodes(case):
    cols = np.unique(case.Pvel.tocoo().col // 3)
    sens = np.unique(case.Asens.tocoo().col // 3)
    return np.unique(np.concatenate([cols, sens]))


def write_inp(case, path, bands, nmodes=60, zeta=None, loads=None):
    slab = case.slab; F = case.F if loads is None else loads
    zeta = slab.eta / 2 if zeta is None else zeta
    xyz = slab.node_xyz()
    L = []
    L.append('** CalculiX input generated by ccx_runner.py  (t=%.3f buried=%s dx=%.4f)' % (case.t, case.buried, slab.dx))
    L.append('*NODE')
    L += ['%d,%.8f,%.8f,%.8f' % (i + 1, *xyz[i]) for i in range(slab.nn)]
    L.append('*ELEMENT, TYPE=C3D8I, ELSET=EALL')
    order = [0, 1, 3, 2, 4, 5, 7, 6]
    L += ['%d,' % (e + 1) + ','.join(str(case.slab.conn[e, o] + 1) for o in order) for e in range(len(slab.conn))]
    L += ['*MATERIAL, NAME=CONC', '*ELASTIC', '%.6e,%.4f' % (slab.E, slab.nu), '*DENSITY', '%.4f' % slab.rho,
          '*SOLID SECTION, ELSET=EALL, MATERIAL=CONC']
    # soil impedance from the same diagonal matrices as the in-house model
    Ak, Ac = slab.soil_matrices(case.soil, case.faces)
    ak = Ak.diagonal(); ac = Ac.diagonal()
    gid = slab.nn; eid = len(slab.conn)
    gnodes = []; groups_k, groups_c = {}, {}
    for kind, arr, groups in (('k', ak, groups_k), ('c', ac, groups_c)):
        for dof in np.nonzero(arr)[0]:
            node, comp = divmod(int(dof), 3)
            key = '%.6e' % arr[dof]
            groups.setdefault(key, []).append((node, comp))
    L.append('*NODE')
    ground_ids = []
    created = {}
    def ground(node, comp):
        nonlocal gid
        key = (node, comp)
        if key not in created:
            gid += 1; p = xyz[node].copy(); p[comp] -= 1.0
            created[key] = gid; L.append('%d,%.8f,%.8f,%.8f' % (gid, *p)); ground_ids.append(gid)
        return created[key]
    elem_lines = []
    for kind, groups, etype, card in (('k', groups_k, 'SPRINGA', '*SPRING'), ('c', groups_c, 'DASHPOTA', '*DASHPOT')):
        for gi, (val, items) in enumerate(groups.items()):
            name = '%s%d' % (kind.upper(), gi)
            elem_lines.append('*ELEMENT, TYPE=%s, ELSET=%s' % (etype, name))
            for node, comp in items:
                eid += 1; elem_lines.append('%d,%d,%d' % (eid, ground(node, comp), node + 1))
            elem_lines.append('%s, ELSET=%s' % (card, name)); elem_lines.append(val if '.' in val else val)
    L += elem_lines
    if ground_ids:
        L.append('*NSET, NSET=GND')
        L += [','.join(str(g) for g in ground_ids[i:i + 12]) for i in range(0, len(ground_ids), 12)]
    sn = surface_nodes(case)
    L.append('*NSET, NSET=SURF')
    L += [','.join(str(int(n) + 1) for n in sn[i:i + 12]) for i in range(0, len(sn), 12)]
    if ground_ids:
        L.append('*BOUNDARY'); L.append('GND,1,3')
    L += ['*STEP', '*FREQUENCY, STORAGE=YES', '%d' % nmodes, '*NODE PRINT, NSET=SURF, FREQUENCY=0', 'U', '*END STEP']
    for c in range(F.shape[1]):
        nz = np.nonzero(F[:, c])[0]
        for bi, (a, b, n) in enumerate(bands):
            L += ['*STEP', '*STEADY STATE DYNAMICS', '%.6f,%.6f,%d,3.0' % (a, b, n),
                  '*MODAL DAMPING, MODAL=DIRECT', '1,%d,%.6f' % (nmodes, zeta), '*CLOAD, OP=NEW']
            L += ['%d,%d,%.9e' % (d // 3 + 1, d % 3 + 1, F[d, c]) for d in nz]
            L += ['*NODE PRINT, NSET=SURF', 'U', '*END STEP']
    pathlib.Path(path).write_text('\n'.join(L) + '\n', encoding='ascii')
    return sn


def run_ccx(jobdir, name, log=None, threads=4):
    env = dict(os.environ, OMP_NUM_THREADS=str(threads), CCX_NPROC_EQUATION_SOLVER=str(threads))
    t = time.time()
    r = subprocess.run([CCX, '-i', name], cwd=jobdir, env=env, capture_output=True, text=True)
    if log: pathlib.Path(log).write_text(r.stdout + r.stderr, encoding='utf-8')
    return r.returncode, time.time() - t, r.stdout


_blk = re.compile(r' displacements \(vx,vy,vz\) for set (\w+) and time\s+([0-9.Ee+-]+)\s*\n\n((?:[ \t]*\d+(?:\s+[-+0-9.Ee]+){3}\s*\n)+)')


def _fix_exp(txt):
    """Fortran prints 3-digit exponents without the 'E' (1.234567-100); restore it."""
    return re.sub(r'(?<=[0-9])([-+][0-9]{3})(?=\s|$)', r'E', txt)


def parse_dat(path, nsurf):
    """Return list of (freq, U complex (nsurf,3), node ids) ordered; pairs of blocks real/imag per frequency; plus eigenfrequencies."""
    txt = pathlib.Path(path).read_text(encoding='ascii', errors='ignore')
    first = txt.split('S T E P       2')[0]
    eig = [float(m.group(1)) for m in re.finditer(r'^\s+\d+\s+[-+0-9.E]+\s+[-+0-9.E]+\s+([-+0-9.E]+)\s+[-+0-9.E]+\s*$', first, re.M)]
    steps = re.split(r'\n\s+S T E P\s+(\d+)\s*\n', txt)
    # steps: [pre, '1', body1, '2', body2, ...]
    out = []
    for i in range(1, len(steps), 2):
        body = steps[i + 1] + chr(10)
        blocks = []
        for m in _blk.finditer(body):
            arr = np.fromstring(_fix_exp(m.group(3)), sep=' ').reshape(-1, 4)
            blocks.append((float(m.group(2)), arr))
        out.append(blocks)
    return eig, out


def collect(path, nsurf, ncol, bands):
    """-> freq (nf,), ids (nsurf,), U (ncol, nf, nsurf, 3) complex (real block + 1j*imag block)."""
    eig, steps = parse_dat(path, nsurf)
    nb = len(bands)
    U = []; fr = None
    for c in range(ncol):
        parts = []; ff = []
        for bi in range(nb):
            blocks = steps[1 + c * nb + bi]
            assert len(blocks) % 2 == 0, (c, bi, len(blocks))
            for j in range(0, len(blocks), 2):
                (f1, a), (f2, b) = blocks[j], blocks[j + 1]
                assert abs(f1 - f2) < 1e-6 * max(1, f1)
                parts.append(a[:, 1:4] + 1j * b[:, 1:4]); ff.append(f1)
                ids = a[:, 0].astype(int)
        U.append(np.array(parts)); fr = np.array(ff)
    return fr, ids, np.array(U), eig
